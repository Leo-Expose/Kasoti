package dev.kasoti.eval.suites

import dev.kasoti.factory.DocAggregator
import dev.kasoti.factory.MacroGate
import dev.kasoti.factory.ProcessClassifier
import dev.kasoti.factory.ProcessLabel
import dev.kasoti.threshold.ThresholdName
import dev.kasoti.threshold.ThresholdRegistry
import dev.kasoti.eval.gate.GateResult
import dev.kasoti.eval.gate.GateStatus
import dev.kasoti.eval.run.Histogram
import dev.kasoti.eval.run.Metric
import dev.kasoti.eval.run.TableData
import dev.kasoti.evalmetrics.Classification
import dev.kasoti.evalmetrics.ClassificationMetrics
import dev.kasoti.evalmetrics.SpecGates

/**
 * Scoring the shipped model over the committed specimen patches (FR-F1, SPEC.md §7).
 *
 * Split out of [MacroSuite] for the same reason the suite's own comment gives for splitting the
 * features check from the classification check: they answer different questions and the
 * difference is the difference between "the extractor runs" and "the weights are any good", and
 * mixing them is how a pipeline check ends up quoted as a result.
 */
internal object MacroClassification {

    /** SPEC.md §7's RED-use floor. A SPEC number, so it is named rather than registry-tuned. */
    const val RECALL_FLOOR: Double = 0.85

    class ClassificationReport(
        val gate: GateResult,
        val metrics: List<Metric>,
        val table: TableData,
        val marginHistogram: Histogram,
        val notes: List<String>,
    )

    /** Column index in the row label list, so a table cell is a number the renderer can print. */
    private fun indexOfLabel(name: String): Int =
        ProcessLabel.entries.indexOfFirst { it.name == name }.takeIf { it >= 0 } ?: -1

    /**
     * Score the model over the committed specimen patches.
     *
     * The specimens replace the older one-patch-per-class `SpectrumPatch` loop, which was a
     * pipeline check: those are seven closed-form recipes, not anything the model was trained on,
     * so a diagonal confusion there proved the plumbing worked and said nothing about the model.
     * The specimens are held-out documents the model has never seen, generated by the same
     * mechanism as the training corpus, and they include the ambiguous patches — so this reports
     * both a classification figure and an abstention figure from one set.
     *
     * n = 1 per class on the report side, and that number is stated in the gate's own `observed`
     * field rather than buried here. One patch per class cannot support a recall; what this can
     * support is "the shipped weights load, they rank each class's own patch first, and a
     * deliberately ambiguous patch falls below the fusion floor".
     */
    fun report(
        registry: ThresholdRegistry,
        model: TrainedModel,
        specimens: List<MacroSpecimenFile>,
    ): ClassificationReport {
        val classifier = ProcessClassifier(model.model)
        val amber = registry[ThresholdName.MACRO_MARGIN_AMBER].toFloat()
        val red = registry[ThresholdName.MACRO_MARGIN_RED].toFloat()

        val classRows = SpecimenFixtures.classSpecimens(specimens)
        val ambiguousRows = SpecimenFixtures.ambiguousSpecimens(specimens)

        // Scored through MacroGate, not ProcessClassifier, so the number reported here is the one
        // the product acts on: the label the system would actually show, with abstention applied.
        val readings = classRows.associate { row ->
            row.id to MacroGate.read(classifier, row.toMacroFeatures(), registry)
        }
        val ambiguousReadings = ambiguousRows.associate { row ->
            row.id to MacroGate.read(classifier, row.toMacroFeatures(), registry)
        }

        val labels = ProcessLabel.entries.map { it.name }
        val orderedLabels = classRows.map { it.label }
        val predicted = orderedLabels.map { row ->
            readings.getValue(classRows.first { it.label == row }.id).label.name
        }
        val metrics: ClassificationMetrics = Classification.of(
            pairs = orderedLabels.zip(predicted),
            labels = labels,
        )

        // Document-level aggregation, which is where the paste/reprint attack shows up. Driven
        // from two *different* classes' specimens so the MISMATCH path is exercised.
        val aggregate = DocAggregator.aggregate(
            photoZone = readings.getValue("specimen-offset").patch,
            textZone = readings.getValue("specimen-laser").patch,
            registry = registry,
        )

        val shared = SpecGates.macroRedUseFloor(metrics, "offset-vs-inkjet", RECALL_FLOOR)
        val synthetic = model.synthetic
        val abstaining = ambiguousReadings.values.count { it.abstained }
        val banner = if (synthetic) MacroSuite.SYNTHETIC_BANNER else "D-MACRO"

        val gate = GateResult(
            id = MacroSuite.GATE_CLASSIFIER,
            name = "Print-process classifier on $banner patches",
            // A synthetic model is SKIPPED, not PASS. It is not a weaker pass, it is not a pass at
            // all: SPEC.md §7's bar is about print processes and this model has never seen one. A
            // green badge on a synthetic number is exactly the thing that gets quoted in a deck
            // six weeks later with the word "synthetic" edited out.
            status = if (synthetic) GateStatus.SKIPPED else GateStatus.PASS,
            bar = MacroSuite.SPEC_BAR + "; RED-use recall floor " + shared.bar,
            observed = "synthetic model, n=" + classRows.size + " held-out specimens (" +
                labels.size + " classes, 1 each); " +
                "margin range %.3f..%.3f; %d/%d ambiguous specimens abstain below %.2f".format(
                    readings.values.minOf { it.margin },
                    readings.values.maxOf { it.margin },
                    abstaining,
                    ambiguousRows.size,
                    amber,
                ),
            detail = (if (synthetic) {
                "NOT the D-MACRO gate of SPEC.md §7 and not gate-eligible: the weights were fitted " +
                    "on textures generated by eval/tools/synth_macros.py, which renders print " +
                    "mechanisms and not ink. " + model.resolution.note + "."
            } else {
                "Trained on D-MACRO, trainingRunId ${model.model.trainingRunId}. " + model.resolution.note + "."
            }) + " " + shared.name + ": " + shared.measured + " (min class recall " +
                "%.1f%%, below-floor classes %s). n=1 per class, so these are not recalls.".format(
                metrics.minRecall * 100,
                metrics.belowRecallFloor(RECALL_FLOOR).ifEmpty { listOf("none") }.joinToString(", "),
            ),
            evidenceRef = model.path,
        )

        val metricList = buildList {
            add(
                Metric(
                    "macro.${model.model.trainingRunId}.accuracy", metrics.accuracy * 100.0, "%",
                    if (synthetic) "synthetic" else "d-macro", MacroSuite.GATE_CLASSIFIER,
                    "n=1 held-out specimen per class; NOT gate-eligible: " + model.banner,
                ),
            )
            for (name in listOf("macro_precision", "macro_recall", "macro_f1")) {
                add(
                    Metric(
                        "macro.${model.model.trainingRunId}.$name", metrics.macroF1 * 100.0, "%",
                        if (synthetic) "synthetic" else "d-macro", MacroSuite.GATE_CLASSIFIER,
                        if (synthetic) "synthetic model and synthetic input" else "d-macro input",
                    ),
                )
            }
            add(
                Metric(
                    "macro.${model.model.trainingRunId}.min_class_recall", metrics.minRecall * 100.0,
                    "%", if (synthetic) "synthetic" else "d-macro", MacroSuite.GATE_CLASSIFIER,
                    "n=1 per class, so this is a pass/fail indicator and not a recall estimate",
                ),
            )
            add(
                Metric(
                    "macro.${model.model.trainingRunId}.classes_below_floor",
                    metrics.belowRecallFloor(RECALL_FLOOR).size.toDouble(), "classes",
                    if (synthetic) "synthetic" else "d-macro", MacroSuite.GATE_CLASSIFIER,
                ),
            )
            add(
                Metric(
                    "macro.agreement", agreementOrdinal(aggregate.agreement).toDouble(), "",
                    if (synthetic) "synthetic" else "d-macro", MacroSuite.GATE_CLASSIFIER,
                    agreementLabel(aggregate.agreement),
                ),
            )
            val split = if (synthetic) "synthetic" else "d-macro"
            add(Metric("macro.margin.red", red.toDouble(), "svm-margin", split, MacroSuite.GATE_CLASSIFIER))
            add(Metric("macro.margin.amber", amber.toDouble(), "svm-margin", split, MacroSuite.GATE_CLASSIFIER))
            add(
                Metric(
                    "macro.ambiguous.abstain_rate",
                    if (ambiguousRows.isEmpty()) 0.0 else abstaining.toDouble() / ambiguousRows.size,
                    "ratio", if (synthetic) "synthetic" else "d-macro", MacroSuite.GATE_CLASSIFIER,
                    "$abstaining of ${ambiguousRows.size} deliberately ambiguous specimens fell below " +
                        "MACRO_MARGIN_AMBER, so the system declined to name a class on them",
                ),
            )
            for (score in metrics.perClass) {
                add(
                    Metric(
                        "macro.per_class.${score.label.lowercase()}.precision", score.precision * 100.0, "%",
                        if (synthetic) "synthetic" else "d-macro", MacroSuite.GATE_CLASSIFIER,
                        "n=${score.support} held-out specimen(s), predicted ${score.predicted}",
                    ),
                )
            }
        }

        val table = TableData(
            name = "Shipped model over the held-out synthetic specimens (n=1 per class)",
            rowLabels = orderedLabels,
            // Label columns carry a `ProcessLabel` *index*, because the table cell type is
            // numeric; the order is spelled out in the note so a reader is never guessing. The
            // `abstained` column is the one that matters, and it is a 0/1 rather than a label
            // because it is the only thing here that changes what the product does.
            columnLabels = listOf("margin", "top class (idx)", "reported (idx)", "abstained 0/1"),
            cells = classRows.map { row ->
                val reading = readings.getValue(row.id)
                listOf(
                    reading.margin.toDouble(),
                    indexOfLabel(reading.patch.label.name).toDouble(),
                    indexOfLabel(reading.label.name).toDouble(),
                    if (reading.abstained) 1.0 else 0.0,
                )
            },
            note = (if (synthetic) "SYNTHETIC. " else "") + "One held-out specimen per class, so this " +
                "proves the shipped weights rank each class's own patch first and nothing more. " +
                "`abstained 1` means the margin fell below MACRO_MARGIN_AMBER and the system " +
                "declined to name a class — for the reject pile that is the desired answer, and " +
                "for a process class it is a defect. Index order: " +
                ProcessLabel.entries.joinToString(", ") { "${it.ordinal}=${it.name}" } +
                ". Per-class recall over a real corpus needs D-MACRO (DATA.md §3).",
        )

        val marginHistogram = Histogram(
            name = "macro_margin_specimens",
            bins = classRows.mapIndexed { index, row ->
                Histogram.Bin(index.toDouble(), index + 1.0, (readings.getValue(row.id).margin * 100.0).toInt())
            } + ambiguousRows.mapIndexed { index, row ->
                val offset = classRows.size + index
                val margin = ambiguousReadings.getValue(row.id).margin
                Histogram.Bin(offset.toDouble(), offset + 1.0, (margin * 100.0).toInt())
            },
            unit = "percentage points",
            split = if (synthetic) "synthetic" else "d-macro",
            note = "One bin per specimen in file order: the seven class specimens first, then the " +
                "ambiguous ones. Height is the softmax margin in percentage points; compare " +
                "against the floor of ${"%.2f".format(amber)} to see which patches the system " +
                "would decline to label.",
        )

        val notes = mutableListOf<String>()
        if (synthetic) {
            notes += "MACRO CLASSIFICATION IS SYNTHETIC: ${model.banner}. " +
                "Model resolution: ${model.resolution.label} — ${model.resolution.note}"
        } else {
            notes += "Macro classification ran on the D-MACRO model ${model.model.trainingRunId}."
        }
        if (classRows.isEmpty()) {
            notes += "No specimen fixtures at ${SpecimenFixtures.PATH}, so only the feature-extraction " +
                "check ran. Regenerate them with eval/tools/synth_macros.py --emit-specimens."
        }
        notes += "Abstention: $abstaining of ${ambiguousRows.size} ambiguous specimens fell below " +
            "MACRO_MARGIN_AMBER $amber, and " +
            "${ambiguousReadings.values.count { it.margin < red }} fell below MACRO_MARGIN_RED $red " +
            "(below which DocAggregator cannot build a MATCH or a MISMATCH)."
        notes += "DocAggregator over an OFFSET photo zone and a LASER text zone reported " +
            "${agreementLabel(aggregate.agreement)}; that is the R-PROC-02 path, exercised on " +
            (if (synthetic) "synthetic" else "D-MACRO") + " input."

        return ClassificationReport(gate, metricList, table, marginHistogram, notes)
    }


    private fun agreementOrdinal(agreement: DocProcessAgreement): Int = when (agreement) {
        DocProcessAgreement.MATCH -> 0
        DocProcessAgreement.MISMATCH -> 1
        DocProcessAgreement.UNCERTAIN -> 2
        DocProcessAgreement.NO_EVIDENCE -> 3
    }

    private fun agreementLabel(agreement: DocProcessAgreement): String = when (agreement) {
        DocProcessAgreement.MATCH -> "MATCH: both zones agree and both are confident"
        DocProcessAgreement.MISMATCH -> "MISMATCH: both margins high — the R-PROC-02 paste/reprint path"
        DocProcessAgreement.UNCERTAIN -> "UNCERTAIN: a margin is low, so the disagreement is not evidence"
        DocProcessAgreement.NO_EVIDENCE -> "NO_EVIDENCE: neither zone produced a usable reading"
    }
}
